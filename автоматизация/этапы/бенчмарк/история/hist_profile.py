def situation_check(text, answer):
    """В описании «о чём речь» не должно быть названия ответа (основ всех его слов от 4 букв)."""
    st = label_stems(answer)
    t = (text or "").lower().replace("ё", "е")
    if st and all(x in t for x in st):
        return f"в описании названо само «{answer}» — опишите, не называя"
    return None


