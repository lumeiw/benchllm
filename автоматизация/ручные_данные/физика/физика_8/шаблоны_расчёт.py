"""Шаблоны расчётных и измерительных заданий (физика, 8 класс).

Устроены как шаблоны 7 класса (ручные_данные/физика/физика_7/шаблоны_расчёт.py): каждый шаблон — функция, которая
по генератору случайных чисел (детерминированному) возвращает одно задание:
  dict(question, answer, unit, tol, steps, explanation[, answer_text, check])
Ответ считает программа, а не модель. Справочные значения (теплоёмкости, теплоты, удельные сопротивления,
плотности, g, e) берутся из справочные_данные.json (таблицы КИМ ОГЭ) и в условии всегда указываются явно.

Норма умения ФОП 8 класса «решать расчётные задачи в 2–3 действия», поэтому расчётные задачи (C) — в 2–3 действия:
перевод единиц, промежуточная величина, итоговая формула. Измерения (M — прямые, I — косвенные, R — исследование
зависимости) построены на лабораторных работах 8 класса из среза.

Поля шаблона: id, concepts (метки понятий среза), requirement (роль умения ФОП: решать, прямые, исследование,
косвенные — код умения у класса подбирается по тексту), family, steps.
"""

SUP = str.maketrans("-0123456789", "⁻⁰¹²³⁴⁵⁶⁷⁸⁹")


def fmt(x, nd=None):
    """Число в русской записи без лишних нулей: 2.50 → «2,5», 13600 → «13 600», 0.0025 → «0,0025»."""
    x = float(x)
    if abs(x - round(x)) < 1e-9 and abs(x) < 1e15:
        return f"{int(round(x)):,}".replace(",", " ")
    s = f"{x:.6g}"
    if "e" in s:
        s = f"{x:.12f}".rstrip("0").rstrip(".")
    return s.replace(".", ",")


def sci(x):
    """Запись с множителем: 2300000 → «2,3·10⁶», 1.6e-19 → «1,6·10⁻¹⁹»."""
    m, e = f"{float(x):.6e}".split("e")
    m = m.rstrip("0").rstrip(".").replace(".", ",")
    return f"{m}·10{str(int(e)).translate(SUP)}"


def plural(n, one, few, many):
    n = abs(int(n))
    if n % 10 == 1 and n % 100 != 11:
        return one
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return few
    return many


def T(id, concepts, req, family, steps):
    def deco(f):
        f.meta = dict(id=id, concepts=concepts, requirement=req, family=family, steps=steps)
        return f
    return deco


