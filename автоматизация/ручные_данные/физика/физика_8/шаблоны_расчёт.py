@T("C.heat", ["Количество теплоты", "Удельная теплоёмкость", "Нагревание"], "решать", "Расчёт", 2)
def c_heat(r):
    name = r.choice(["вода", "алюминий", "медь", "сталь"])
    m = r.choice([200, 250, 400, 500])
    t1 = r.choice([15, 20, 25])
    t2 = r.choice([45, 60, 75] if name == "вода" else [80, 120, 170])
    Q = c_(name) * m / 1000 * (t2 - t1)
    what = "воду" if name == "вода" else f"{ADJ[name]} брусок"
    return dict(question=f"Какое количество теплоты нужно, чтобы нагреть {what} массой {m} г от {t1} до {t2} °C? Удельная теплоёмкость {GEN[name]} {fmt(c_(name))} {C_UNIT}. Ответ дайте в килоджоулях.",
                answer=Q / 1000, unit="кДж",
                explanation=f"m = {m} г = {fmt(m/1000)} кг; Δt = {t2} − {t1} = {t2-t1} °C; Q = c·m·Δt = {fmt(c_(name))}·{fmt(m/1000)}·{t2-t1} = {fmt(Q)} Дж = {fmt(Q/1000)} кДж.")


