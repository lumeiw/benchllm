@T("C.mix", ["Уравнение теплового баланса", "Теплообмен"], "решать", "Расчёт", 2)
def c_mix(r):
    while True:
        m1, m2 = r.choice([1, 2, 3, 4]), r.choice([1, 2, 3])
        t1, t2 = r.choice([10, 15, 20]), r.choice([60, 70, 80, 90])
        th = (m1 * t1 + m2 * t2) / (m1 + m2)
        if abs(th * 2 - round(th * 2)) < 1e-9:
            break
    return dict(question=f"В сосуде смешали {m1} кг воды при {t1} °C и {m2} кг воды при {t2} °C. Какая температура установится? Теплообменом с сосудом и окружающей средой пренебречь. Ответ дайте в °C.",
                answer=th, unit="°C",
                explanation=f"Q отданное = Q полученное: c·{m2}·({t2} − θ) = c·{m1}·(θ − {t1}) ⇒ θ = ({m1}·{t1} + {m2}·{t2})/({m1} + {m2}) = {fmt(th)} °C.")


@T("C.mix_mass", ["Тепловое равновесие", "Уравнение теплового баланса"], "решать", "Расчёт", 3)
def c_mix_mass(r):
    while True:
        m1 = r.choice([2, 3, 4, 6])
        t1, th, t2 = r.choice([10, 20]), r.choice([30, 40, 50]), r.choice([80, 90, 100])
        m2 = m1 * (th - t1) / (t2 - th)
        if abs(m2 * 10 - round(m2 * 10)) < 1e-9:
            break
    return dict(question=f"Сколько килограммов воды при {t2} °C нужно долить к {m1} кг воды при {t1} °C, чтобы установилась температура {th} °C? Потерями теплоты пренебречь. Ответ дайте в килограммах.",
                answer=m2, unit="кг",
                explanation=f"Холодная вода получает Q₁ = c·{m1}·({th} − {t1}), горячая отдаёт Q₂ = c·m·({t2} − {th}); Q₁ = Q₂ ⇒ m = {m1}·{th - t1}/{t2 - th} = {fmt(m2)} кг.")


