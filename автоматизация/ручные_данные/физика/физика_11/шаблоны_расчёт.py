def r_stopping(r):
    A = r.choice([2.0, 2.3, 1.9, 4.5])
    hv = h_() / e_() * 1e15     # эВ на 10¹⁵ Гц
    nus = [1.0, 1.5] if A < 4 else [1.5, 2.0]
    rows = "; ".join(f"ν = {fmt(nu)}·10¹⁵ Гц — U_з = {fmt(hv * nu - A, 3)} В" for nu in nus)
