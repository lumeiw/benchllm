@T("C.thomson_period", ["Формула Томсона", "Идеальный колебательный контур"], "решать", "Расчёт", 1)
def c_thomson(r):
    L, C, k, unit = r.choice([(1e-3, 1e-9, 1e-6, "мкс"), (4e-3, 1e-9, 1e-6, "мкс"), (1e-2, 4e-8, 1e-6, "мкс"), (2e-3, 2e-9, 1e-6, "мкс"), (1e-4, 4e-10, 1e-6, "мкс"), (0.1, 1e-5, 1e-3, "мс")])
    Tp = 2 * PI * math.sqrt(L * C)
    return dict(question=f"Идеальный колебательный контур состоит из катушки индуктивностью {sci(L)} Гн и конденсатора ёмкостью {sci(C)} Ф. Найдите период свободных электромагнитных колебаний в контуре (π = {fmt(PI)}). Ответ дайте в {'микросекундах' if unit == 'мкс' else 'миллисекундах'}.",
                answer=Tp / k, unit=unit, tol=0.01,
                explanation=f"T = 2π√(LC) = 2·{fmt(PI)}·√({sci(L)}·{sci(C)}) = 2·{fmt(PI)}·{sci(math.sqrt(L*C))} = {sci(Tp)} с = {fmt(Tp/k, 4)} {unit}.")


