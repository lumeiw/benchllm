    U = hv * nu - A
    return dict(question=f"Освещая катод фотоэлемента светом разной частоты, ученик измерил запирающее напряжение: {rows}. Каким будет запирающее напряжение при частоте {fmt(nu)}·10¹⁵ Гц? Ответ дайте в вольтах.",
                answer=U, unit="В", tol=0.02,
                explanation=f"По уравнению Эйнштейна eU_з = hν − A: зависимость U_з(ν) линейная, на каждые 0,5·10¹⁵ Гц U_з растёт на {fmt(hv*0.5, 3)} В; U_з = {fmt(hv*nus[1] - A, 3)} + {fmt(hv*0.5, 3)} = {fmt(U, 3)} В.")


