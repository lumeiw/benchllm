import math
import re

SUP = str.maketrans("-0123456789", "⁻⁰¹²³⁴⁵⁶⁷⁸⁹")


def fmt(x, nd=None):
    """Число в русской записи без лишних нулей: 2.50 → «2,5», 13600 → «13 600», 0.0025 → «0,0025»."""
    x = float(x)
    if nd is not None:
        x = round(x, nd)
    if abs(x - round(x)) < 1e-9 and abs(x) < 1e15:
        return f"{int(round(x)):,}".replace(",", " ")
    s = f"{x:.6g}"
    if "e" in s:
        s = f"{x:.12f}".rstrip("0").rstrip(".")
    return s.replace(".", ",")


def sci(x):
    """Запись с множителем: 3e8 → «3·10⁸», 6.6e-34 → «6,6·10⁻³⁴»."""
    m, e = f"{float(x):.6e}".split("e")
    m = m.rstrip("0").rstrip(".").replace(".", ",")
    return f"{m}·10{str(int(e)).translate(SUP)}"


def plural(n, one, few, many):
    n = abs(int(n))
    if n % 10 == 1 and n % 100 != 11:
        return one
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return few
    return many


MINUS = re.compile(r"(?<![\w])-(?=\d)")


def T(id, concepts, req, family, steps):
    """Регистрация шаблона; в тексте задания дефис перед числом заменяется знаком минус (−5 м/с², −13,6 эВ)."""
    def deco(f):
        def g_(r):
            d = f(r)
            for k in ("question", "explanation", "answer_text"):
                if isinstance(d.get(k), str):
                    d[k] = MINUS.sub("−", d[k])
            return d
        g_.__name__ = f.__name__
        g_.meta = dict(id=id, concepts=concepts, requirement=req, family=family, steps=steps)
        return g_
    return deco


