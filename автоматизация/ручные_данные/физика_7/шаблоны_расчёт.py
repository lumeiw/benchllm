@T("C.avg", ["Средняя скорость"], "решать", "Расчёт", 2)
def c_avg(r):
    while True:
        s1, t1 = r.choice([(100, 20), (120, 30), (200, 40), (300, 60)])
        s2, t2 = r.choice([(300, 30), (400, 50), (600, 60), (500, 100)])
        v = (s1 + s2) / (t1 + t2)
        if abs(v - round(v, 1)) < 1e-9 and abs(v - (s1 / t1 + s2 / t2) / 2) > 0.3:
            break
    return dict(question=f"Первые {s1} м лыжник прошёл за {t1} с, следующие {s2} м — за {t2} с. Найдите среднюю скорость лыжника на всём пути. Ответ дайте в м/с.",
                answer=v, unit="м/с",
                explanation=f"vср = (s₁ + s₂)/(t₁ + t₂) = {s1 + s2} м / {t1 + t2} с = {fmt(v)} м/с (не среднее арифметическое скоростей).")


