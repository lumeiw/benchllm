import math


def fmt(x, nd=3):
    """Число в русской записи без лишних нулей: 2.50 → «2,5»."""
    if isinstance(x, int) or float(x).is_integer():
        return f"{int(round(x)):,}".replace(",", " ")
    s = f"{x:.{nd}f}".rstrip("0").rstrip(".")
    return s.replace(".", ",")


def plural(n, one, few, many):
    n = abs(int(n))
    if n % 10 == 1 and n % 100 != 11:
        return one
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return few
    return many


def T(id, concepts, req, family, steps):
    def deco(f):
        f.meta = dict(id=id, concepts=concepts, requirement=req, family=family, steps=steps)
        return f
    return deco


REF = {}  # заполняется генератором из справочные_данные.json


def rho(name):
    return REF["плотность_жидкостей"].get(name) or REF["плотность_твёрдых"][name]


